from pydantic import BaseModel, Field


class RPEPredictRequest(BaseModel):
    temperature_c: float = Field(
        ...,
        ge=-10.0,
        le=60.0,
        description="Ambient gym/training temperature in Celsius (-10.0 to 60.0)",
        examples=[30.0],
    )
    humidity_pct: float = Field(
        ...,
        ge=0.0,
        le=100.0,
        description="Relative ambient humidity percentage (0.0 to 100.0)",
        examples=[75.0],
    )
    air_quality_index: float = Field(
        ...,
        ge=0.0,
        le=500.0,
        description="Air Quality Index (AQI) (0.0 to 500.0)",
        examples=[50.0],
    )
    sleep_hours: float = Field(
        ...,
        ge=0.0,
        le=24.0,
        description="Total sleep duration in hours (0.0 to 24.0)",
        examples=[7.0],
    )
    sleep_quality_1_5: float = Field(
        ...,
        ge=1.0,
        le=5.0,
        description="Subjective sleep recovery quality rating (1.0 to 5.0 scale)",
        examples=[3.0],
    )
    mood_readiness_1_5: float = Field(
        ...,
        ge=1.0,
        le=5.0,
        description="Subjective mood and pre-training readiness rating (1.0 to 5.0 scale)",
        examples=[3.0],
    )
    planned_duration_min: float = Field(
        ...,
        gt=0.0,
        le=360.0,
        description="Planned workout duration in minutes (1.0 to 360.0)",
        examples=[60.0],
    )
    planned_intensity_1_10: float = Field(
        ...,
        ge=1.0,
        le=10.0,
        description="Planned session intensity rating (1.0 to 10.0 scale)",
        examples=[7.0],
    )
    workout_type: str = Field(
        default="Mixed Strength",
        min_length=1,
        max_length=100,
        description="Workout classification (e.g., 'Mixed Strength', 'Squat', 'Bench Press', 'Deadlift')",
        examples=["Bench Press"],
    )


class RPEPredictResponse(BaseModel):
    predicted_session_rpe: float = Field(
        ...,
        description="Predicted Borg CR-10 Session Rating of Perceived Exertion (RPE)",
        examples=[5.49],
    )
    model_name: str = Field(
        ...,
        description="Name of the underlying trained ML model",
        examples=["ridge"],
    )
    model_variant: str = Field(
        default="baseline",
        description="Configured RPE model variant ('baseline' or 'pp1_optimized')",
        examples=["baseline"],
    )
    model_version: str = Field(
        default="unavailable",
        description="Model artifact identity: variant plus SHA-256 prefix of the loaded artifact file",
        examples=["baseline+sha256:0123456789ab"],
    )
    model_status: str = Field(
        default="DEVELOPMENT_ONLY",
        description="Scientific validation status flag",
    )
    message: str = Field(
        default="This prediction was generated by a development model trained strictly on synthetic data and has NOT been validated for real athlete decisions or clinical load management.",
        description="Mandatory scientific advisory notice",
    )
